"""Writes app/ui/cities.js: where each city of the game lies in the real world (latitude,
longitude), for the weather card. The cities are the ones in app/ui/places.js (run
tools/build_places.py first); their places come from Open-Meteo's geocoding service, the
most populous match of the city's name in its country.

    python tools/build_cities.py

The game's map is the real one through a Lambert conformal conic projection (standard
parallels 37 and 65, origin 50 N 15 E), drawn 1:19.08 on the mainland and 1:14.14 in the UK.
The scale and offsets in app/ui/weather.js were fitted to 108 cities whose game coordinates
are known (10 km off on average on the mainland, 6 km in the UK).
"""
import json, os, sys, time, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLACES = os.path.join(ROOT, "app", "ui", "places.js")
OUT = os.path.join(ROOT, "app", "ui", "cities.js")

CODES = {
    "albania": "AL", "austria": "AT", "belgium": "BE", "bosnia": "BA", "bulgaria": "BG", "croatia": "HR",
    "czech": "CZ", "denmark": "DK", "estonia": "EE", "finland": "FI", "france": "FR", "germany": "DE",
    "greece": "GR", "hungary": "HU", "iceland": "IS", "italy": "IT", "kosovo": "XK", "latvia": "LV",
    "lithuania": "LT", "luxembourg": "LU", "macedonia": "MK", "montenegro": "ME", "netherlands": "NL",
    "norway": "NO", "poland": "PL", "portugal": "PT", "romania": "RO", "russia": "RU", "serbia": "RS",
    "slovakia": "SK", "slovenia": "SI", "spain": "ES", "sweden": "SE", "switzerland": "CH", "turkey": "TR",
    "uk": "GB",
}
# Border crossings and small places the geocoding service does not know as towns.
MANUAL = {
    "artand": [47.122, 21.936], "corticadas": [38.776, -8.399], "europoort": [51.948, 4.135],
    "giurgiu": [43.903, 25.969], "hamzabeyli": [42.058, 26.614], "kapikule": [41.716, 26.357],
    "mitilini": [39.107, 26.555], "nadlac": [46.167, 20.751], "olkiluoto": [61.236, 21.444],
    "patras": [38.246, 21.735],
}
# A city's name in its own country's language, where the screen has that language.
NATIVE = {"germany": "de", "austria": "de", "switzerland": "de", "poland": "pl", "france": "fr", "belgium": "fr",
          "luxembourg": "fr", "spain": "es", "russia": "ru", "turkey": "tr"}


def search(name, code):
    q = urllib.parse.urlencode({"name": name, "count": 20, "language": "en", "format": "json", "countryCode": code})
    for attempt in range(3):
        try:
            with urllib.request.urlopen("https://geocoding-api.open-meteo.com/v1/search?" + q, timeout=20) as r:
                results = json.load(r).get("results") or []
            break
        except OSError:
            time.sleep(2)
    else:
        return None
    hits = [h for h in results if h.get("country_code") == code and h.get("feature_code", "").startswith("PPL")]
    if not hits:
        return None
    return max(hits, key=lambda h: h.get("population") or 0)


def main():
    text = open(PLACES, encoding="utf-8").read()
    cities = json.loads(text[text.index("{"):text.rindex("}") + 1])["cities"]
    found, missing = {}, []
    for cid, (country, names) in sorted(cities.items()):
        if cid in MANUAL:
            found[cid] = MANUAL[cid]
            continue
        code = CODES.get(country)
        tries = [names["en"]]
        if names.get(NATIVE.get(country, "")) and names[NATIVE[country]] not in tries:
            tries.append(names[NATIVE[country]])
        hit = None
        for name in tries:
            hit = code and search(name, code)
            time.sleep(0.12)
            if hit:
                break
        if hit:
            found[cid] = [round(hit["latitude"], 3), round(hit["longitude"], 3)]
        else:
            missing.append(cid)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build_cities.py: where the game's cities lie in the real world\n")
        f.write("// (latitude, longitude), by the game's ids. Do not edit by hand.\n")
        f.write("window.CABINPLAY_CITIES = " + json.dumps(found, separators=(",", ":"), sort_keys=True) + ";\n")
    print(f"wrote {OUT}: {len(found)} cities, {len(missing)} not found: {' '.join(missing)}")


if __name__ == "__main__":
    sys.exit(main())
