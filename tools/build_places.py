"""Writes app/ui/places.js: the game's city and country names in the screen's languages.

The telemetry API names a job's cities in their local language and script (Mytilene
arrives as "Μυτιλήνη" whatever language the game is in), so the screen looks them up by
the city id instead. The names come from the game's own definitions and translations.

Run it again after SCS adds a map expansion:

    python tools/build_places.py "<Euro Truck Simulator 2 folder>"

Needs tools/extractor/extractor.exe (sk-zk's SCS extractor, not part of the repository).
"""
import glob
import io
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTRACTOR = os.path.join(ROOT, "tools", "extractor", "extractor.exe")
WORK = os.path.join(ROOT, "build", "places")
OUT = os.path.join(ROOT, "app", "ui", "places.js")

# screen language -> the game's locale folder
LOCALES = {"en": "en_gb", "tr": "tr_tr", "de": "de_de", "pl": "pl_pl", "fr": "fr_fr", "es": "es_es", "ru": "ru_ru"}


def extract(game):
    if os.path.isdir(WORK):
        shutil.rmtree(WORK)
    archives = sorted(glob.glob(os.path.join(game, "*.scs")))
    # Base game first, so the map expansions' definitions win where they change a city.
    archives.sort(key=lambda a: (not os.path.basename(a).startswith(("def", "base")), a))
    for archive in archives:
        name = os.path.splitext(os.path.basename(archive))[0]
        if name == "locale":
            args = [EXTRACTOR, archive, "-D", "-d", os.path.join(WORK, "locale"), "-q"]
        else:
            args = [EXTRACTOR, archive, "-d", os.path.join(WORK, "def", name), "-p=/def/city,/def/country", "-q"]
        subprocess.run(args, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return archives


def read(path):
    return io.open(path, encoding="utf-8", errors="replace").read()


def unquote(text):
    return text.replace('\\"', '"').replace("\\\\", "\\")


def translations(locale):
    table = {}
    folder = os.path.join(WORK, "locale", "locale", locale)
    for path in sorted(glob.glob(os.path.join(folder, "*.su[ii]")) + glob.glob(os.path.join(folder, "*.sii"))):
        keys = re.findall(r'key\[\]\s*:\s*"((?:[^"\\]|\\.)*)"\s*\n\s*val\[\]\s*:\s*"((?:[^"\\]|\\.)*)"', read(path))
        for key, val in keys:
            table[key] = unquote(val)
    return table


def localized(value, tables, fallback):
    """'@@key@@' in every language, or the plain name everywhere."""
    m = re.fullmatch(r"@@(.+)@@", value or "")
    names = {}
    for lang, table in tables.items():
        names[lang] = table.get(m.group(1), fallback) if m else (value or fallback)
    return names


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    game = sys.argv[1]
    extract(game)
    tables = {lang: translations(locale) for lang, locale in LOCALES.items()}

    countries = {}
    for path in glob.glob(os.path.join(WORK, "def", "*", "def", "country", "*.sui")):
        text = read(path)
        m = re.search(r"country_data\s*:\s*country\.data\.(\w+)", text)
        if not m:
            continue
        native = re.search(r'\bname\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        key = re.search(r'name_localized\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        countries[m.group(1).lower()] = localized(key and key.group(1), tables, native and unquote(native.group(1)) or m.group(1))

    cities = {}
    for path in sorted(glob.glob(os.path.join(WORK, "def", "*", "def", "city", "*.sui"))):
        text = read(path)
        m = re.search(r"city_data\s*:\s*city\.(\w+)", text)
        if not m:
            continue
        native = re.search(r'city_name\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        key = re.search(r'city_name_localized\s*:\s*"((?:[^"\\]|\\.)*)"', text)
        country = re.search(r"\bcountry\s*:\s*(\w+)", text)
        names = localized(key and key.group(1), tables, native and unquote(native.group(1)) or m.group(1))
        # ids are case-insensitive in the game ("pecs" names its country "Hungary")
        cities[m.group(1).lower()] = [country.group(1).lower() if country else "", names]

    def compact(names):
        # English is always there; the others only where they differ from it.
        return {lang: name for lang, name in names.items() if lang == "en" or name != names["en"]}

    data = {
        "countries": {k: compact(v) for k, v in sorted(countries.items())},
        "cities": {k: [c, compact(n)] for k, (c, n) in sorted(cities.items())},
    }
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/build_places.py from the game's own files: city and country names\n"
                "// in the screen's languages, by the game's ids. Do not edit by hand.\n"
                "window.CABINPLAY_PLACES = %s;\n" % body)
    print("wrote %s: %d cities, %d countries, %d KB" % (os.path.relpath(OUT, ROOT), len(cities), len(countries),
                                                       os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    main()
